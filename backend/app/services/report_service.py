            ["Sport Discipline", athlete.sport_type or "Athletics", "Position", athlete.position or "Field"],
            ["Athlete Age", f"{athlete.age or 22} yrs", "Stature / Weight", f"{athlete.height_cm or 180:.0f} cm / {athlete.weight_kg or 75:.1f} kg"],
