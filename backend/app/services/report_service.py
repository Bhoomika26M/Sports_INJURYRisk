            for c_i, val in enumerate(krow, start=1):
                cell = ws1.cell(row=idx, column=c_i, value=val)
                cell.font = bold_font if c_i <= 2 else cell_font
                cell.border = thin_border
                if is_alt:
                    cell.fill = alt_fill

